-- Schema completo da plataforma (dicionário em CLAUDE.md), numa sintaxe aceita
-- pelo PostgreSQL e pelo H2 (MODE=PostgreSQL): DEFAULT antes das restrições,
-- TIMESTAMP WITH TIME ZONE, CURRENT_TIMESTAMP, IDENTITY em vez de SERIAL e ids UUID gerados pela
-- aplicação. Novas migrações seguem estas mesmas regras e valem para os dois.

-- Lava-jatos atendidos pela instalação.
CREATE TABLE estabelecimentos (
    id UUID PRIMARY KEY,
    slug VARCHAR(60) NOT NULL,
    nome VARCHAR(100) NOT NULL,
    hora_abertura INT DEFAULT 8 NOT NULL CHECK (hora_abertura BETWEEN 0 AND 23),
    hora_fechamento INT DEFAULT 18 NOT NULL CHECK (hora_fechamento BETWEEN 1 AND 24),
    abre_domingo BOOLEAN DEFAULT FALSE NOT NULL,
    max_veiculos_hora INT DEFAULT 3 NOT NULL CHECK (max_veiculos_hora > 0),
    ativo BOOLEAN DEFAULT TRUE NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_estabelecimentos_slug UNIQUE (slug),
    CONSTRAINT ck_estabelecimentos_horario CHECK (hora_abertura < hora_fechamento)
);

-- Administrador da plataforma (fora de qualquer lava-jato).
CREATE TABLE administradores (
    id UUID PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_administradores_email UNIQUE (email)
);

CREATE TABLE usuarios (
    id UUID PRIMARY KEY,
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimentos (id),
    nome VARCHAR(100) NOT NULL,
    telefone VARCHAR(20),
    -- Login da gestão; único na plataforma, guardado em minúsculas.
    email VARCHAR(254),
    senha_hash VARCHAR(255),
    perfil VARCHAR(20) NOT NULL CHECK (perfil IN ('CLIENTE', 'LAVADOR', 'GERENTE')),
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ativo BOOLEAN DEFAULT TRUE NOT NULL,
    -- Crachá do lavador: PIN (BCrypt) e HMAC do token do QR.
    pin_hash VARCHAR(255),
    cracha_hash VARCHAR(64),
    pin_tentativas INT DEFAULT 0 NOT NULL,
    pin_bloqueado_ate TIMESTAMP WITH TIME ZONE,
    google_sub VARCHAR(255),
    CONSTRAINT uq_usuarios_email UNIQUE (email),
    CONSTRAINT uq_usuarios_telefone UNIQUE (estabelecimento_id, telefone),
    CONSTRAINT uq_usuarios_cracha UNIQUE (cracha_hash),
    CONSTRAINT uq_usuarios_google UNIQUE (estabelecimento_id, google_sub)
);

CREATE TABLE veiculos (
    id UUID PRIMARY KEY,
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimentos (id),
    cliente_id UUID REFERENCES usuarios (id),
    placa VARCHAR(10) NOT NULL,
    modelo VARCHAR(50),
    cor VARCHAR(30),
    -- Contato do dono quando o veículo não tem conta (entrada pelo gerente).
    contato_nome VARCHAR(100),
    contato_telefone VARCHAR(20),
    CONSTRAINT uq_veiculos_placa UNIQUE (estabelecimento_id, placa)
);

CREATE TABLE servicos_preco (
    id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimentos (id),
    nome VARCHAR(50) NOT NULL,
    preco DECIMAL(10, 2) NOT NULL,
    comissao_lavador DECIMAL(10, 2)
);

CREATE INDEX idx_servicos_preco_estabelecimento ON servicos_preco (estabelecimento_id);

CREATE TABLE atendimentos (
    id UUID PRIMARY KEY,
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimentos (id),
    veiculo_id UUID NOT NULL REFERENCES veiculos (id),
    servico_preco_id INT NOT NULL REFERENCES servicos_preco (id),
    lavador_id UUID REFERENCES usuarios (id),
    status VARCHAR(25) DEFAULT 'AGENDADO' NOT NULL,
    data_agendamento TIMESTAMP WITH TIME ZONE NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    lavagem_iniciada_em TIMESTAMP WITH TIME ZONE,
    lavagem_concluida_em TIMESTAMP WITH TIME ZONE,
    previsao_entrega TIMESTAMP WITH TIME ZONE,
    observacoes VARCHAR(500),
    -- Link público do ticket (sem login).
    ticket_token VARCHAR(64),
    CONSTRAINT uq_atendimentos_ticket UNIQUE (ticket_token)
);

-- Fila do pátio (status + atualizado_em) e agenda, sempre dentro do lava-jato.
CREATE INDEX idx_atendimentos_estabelecimento_status
    ON atendimentos (estabelecimento_id, status, atualizado_em);
CREATE INDEX idx_atendimentos_estabelecimento_agenda
    ON atendimentos (estabelecimento_id, data_agendamento);

CREATE TABLE pagamentos (
    id UUID PRIMARY KEY,
    atendimento_id UUID NOT NULL REFERENCES atendimentos (id),
    forma_pagamento VARCHAR(20) NOT NULL
        CHECK (forma_pagamento IN ('CASH', 'PIX', 'DEBIT_CARD', 'CREDIT_CARD')),
    valor DECIMAL(10, 2) NOT NULL,
    recebido_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_pagamentos_atendimento UNIQUE (atendimento_id)
);

CREATE TABLE comissoes_lavador (
    id UUID PRIMARY KEY,
    atendimento_id UUID NOT NULL REFERENCES atendimentos (id),
    lavador_id UUID NOT NULL REFERENCES usuarios (id),
    valor DECIMAL(10, 2) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_comissoes_lavador_lavador_id ON comissoes_lavador (lavador_id);

CREATE TABLE pausas_atendimento (
    id UUID PRIMARY KEY,
    atendimento_id UUID NOT NULL REFERENCES atendimentos (id),
    lavador_id UUID NOT NULL REFERENCES usuarios (id),
    motivo VARCHAR(20) NOT NULL CHECK (motivo IN ('LUNCH', 'RESTROOM', 'OTHER')),
    descricao VARCHAR(200),
    iniciada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    retomada_em TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_pausas_atendimento_order ON pausas_atendimento (atendimento_id);

-- Checklist de entrada/saída; itens = lista JSON guardada como texto.
CREATE TABLE service_order_checklist (
    id UUID PRIMARY KEY,
    atendimento_id UUID NOT NULL REFERENCES atendimentos (id),
    tipo VARCHAR(6) NOT NULL CHECK (tipo IN ('ENTRY', 'EXIT')),
    itens TEXT DEFAULT '[]' NOT NULL,
    assinatura_imagem TEXT,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    criado_por UUID REFERENCES usuarios (id),
    CONSTRAINT uq_checklist_atendimento_tipo UNIQUE (atendimento_id, tipo)
);

CREATE TABLE service_order_photo (
    id UUID PRIMARY KEY,
    atendimento_id UUID NOT NULL REFERENCES atendimentos (id) ON DELETE CASCADE,
    tipo VARCHAR(6) NOT NULL CHECK (tipo IN ('ENTRY', 'EXIT')),
    imagem_data TEXT NOT NULL,
    descricao TEXT,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    criado_por UUID REFERENCES usuarios (id)
);

CREATE INDEX idx_service_order_photo_atendimento_id ON service_order_photo (atendimento_id);

CREATE TABLE expense_category (
    id UUID PRIMARY KEY,
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimentos (id),
    nome VARCHAR(100) NOT NULL,
    cor VARCHAR(7) DEFAULT '#6B7280' NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE cash_transaction (
    id UUID PRIMARY KEY,
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimentos (id),
    tipo VARCHAR(8) NOT NULL CHECK (tipo IN ('INCOME', 'EXPENSE')),
    valor DECIMAL(10, 2) NOT NULL,
    categoria_id UUID REFERENCES expense_category (id),
    descricao TEXT,
    data_referencia DATE NOT NULL,
    atendimento_id UUID REFERENCES atendimentos (id),
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    criado_por UUID REFERENCES usuarios (id)
);

CREATE INDEX idx_cash_transaction_estabelecimento_data
    ON cash_transaction (estabelecimento_id, data_referencia);
CREATE INDEX idx_cash_transaction_categoria_id ON cash_transaction (categoria_id);

-- Venda rápida no balcão e orçamento.
CREATE TABLE vendas (
    id UUID PRIMARY KEY,
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimentos (id),
    tipo VARCHAR(12) NOT NULL CHECK (tipo IN ('VENDA', 'ORCAMENTO')),
    veiculo_id UUID REFERENCES veiculos (id),
    cliente_nome VARCHAR(100),
    cliente_telefone VARCHAR(20),
    subtotal DECIMAL(10, 2) NOT NULL,
    desconto DECIMAL(10, 2) DEFAULT 0 NOT NULL,
    total DECIMAL(10, 2) NOT NULL,
    observacoes VARCHAR(500),
    criado_por UUID REFERENCES usuarios (id),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_vendas_estabelecimento_criado_em ON vendas (estabelecimento_id, criado_em);

CREATE TABLE venda_itens (
    id UUID PRIMARY KEY,
    venda_id UUID NOT NULL REFERENCES vendas (id) ON DELETE CASCADE,
    servico_preco_id INT NOT NULL REFERENCES servicos_preco (id),
    descricao VARCHAR(50) NOT NULL,
    quantidade INT NOT NULL CHECK (quantidade > 0),
    preco_unitario DECIMAL(10, 2) NOT NULL,
    total DECIMAL(10, 2) NOT NULL
);

CREATE INDEX idx_venda_itens_venda_id ON venda_itens (venda_id);

CREATE TABLE venda_pagamentos (
    id UUID PRIMARY KEY,
    venda_id UUID NOT NULL REFERENCES vendas (id) ON DELETE CASCADE,
    forma_pagamento VARCHAR(20) NOT NULL
        CHECK (forma_pagamento IN ('CASH', 'PIX', 'DEBIT_CARD', 'CREDIT_CARD')),
    valor DECIMAL(10, 2) NOT NULL CHECK (valor > 0),
    recebido_em TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_venda_pagamentos_venda_id ON venda_pagamentos (venda_id);

-- Códigos de acesso por WhatsApp (só o hash; um ativo por telefone e lava-jato).
CREATE TABLE codigos_acesso (
    id UUID PRIMARY KEY,
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimentos (id),
    telefone VARCHAR(20) NOT NULL,
    codigo_hash VARCHAR(64) NOT NULL,
    tentativas INT DEFAULT 0 NOT NULL,
    expira_em TIMESTAMP WITH TIME ZONE NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_codigos_acesso_telefone ON codigos_acesso (estabelecimento_id, telefone);
